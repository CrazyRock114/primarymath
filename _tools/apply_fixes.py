def main() -> int:
    ok = miss = 0
    for rel, old, new, why in FIXES:
        p = os.path.join(SITE, rel)
        if not os.path.exists(p):
            print(f"  ✗ 文件不存在 {rel}")
            miss += 1
            continue
        s = open(p, encoding="utf-8").read()
        if old not in s:
            print(f"  ✗ 未命中 {rel}  ← {why}")
            print(f"      找的是: {old[:70]}")
            miss += 1
            continue
        if s.count(old) > 1:
            print(f"  ⚠️ {rel} 出现 {s.count(old)} 次，只改第一处 ← {why}")
        open(p, "w", encoding="utf-8").write(s.replace(old, new, 1))
        print(f"  ✓ {rel}  ← {why}")
        ok += 1
    print(f"\n修复 {ok} 条，未命中 {miss} 条，共 {len(FIXES)} 条")
    return 1 if miss else 0


if __name__ == "__main__":
    sys.exit(main())
